// The "Add Bounded Context" command: ask for a name, run `scaffold add module`.
import { promises as fs } from "node:fs";
import * as path from "node:path";
import * as vscode from "vscode";

import { ENTITY_NAME, MODULE_NAME, locateBinary, runAddModule } from "../scaffold/cli";
import { reportFailure } from "./init";

const CONFIG_SECTION = "goDddScaffold";

/** addBoundedContext is the handler registered for the command. `uri` is set
 * when the command comes from the explorer context menu. */
export async function addBoundedContext(
	output: vscode.OutputChannel,
	uri?: vscode.Uri,
): Promise<void> {
	const projectDir = await findProjectRoot(uri);
	if (!projectDir) {
		void vscode.window.showErrorMessage(
			"No project generated by scaffold init found: open its folder (the one with go.mod and cmd/modules.go).",
		);
		return;
	}

	const name = await vscode.window.showInputBox({
		title: "Bounded context name",
		prompt: "Folder under internal/, route under /api, table prefix.",
		placeHolder: "billing",
		ignoreFocusOut: true,
		validateInput: (v) =>
			MODULE_NAME.test(v.trim()) ? undefined : "Lowercase letters and digits, starting with a letter.",
	});
	if (name === undefined) {
		return;
	}
	const entity = await vscode.window.showInputBox({
		title: "Aggregate type name",
		prompt: "Leave empty to use the module name, capitalised.",
		placeHolder: "Invoice",
		ignoreFocusOut: true,
		validateInput: (v) =>
			v.trim() === "" || ENTITY_NAME.test(v.trim()) ? undefined : "A CamelCase Go type name, e.g. Invoice.",
	});
	if (entity === undefined) {
		return;
	}

	const configured = vscode.workspace.getConfiguration(CONFIG_SECTION).get<string>("binaryPath", "");
	try {
		const { command, version } = await locateBinary(configured);
		output.appendLine(`> ${command} (${version})`);
		const { result, output: cliOutput } = await runAddModule(command, projectDir, name.trim(), { entity });
		output.append(cliOutput);

		const created = result.created.length;
		const msg = created > 0
			? `Module ${name.trim()}: ${created} file(s) created. Its routes are under /api/${name.trim()}.`
			: `Module ${name.trim()} already exists: nothing was overwritten.`;
		const open = "Open domain model";
		const picked = await vscode.window.showInformationMessage(msg, ...(created > 0 ? [open] : []));
		if (picked === open) {
			const model = vscode.Uri.file(path.join(projectDir, "internal", name.trim(), "domain", "model.go"));
			await vscode.window.showTextDocument(await vscode.workspace.openTextDocument(model));
		}
	} catch (err) {
		await reportFailure(err, output);
	}
}

/** findProjectRoot walks up from the picked folder (or the workspace folder) to
 * the directory holding cmd/modules.go. */
async function findProjectRoot(uri?: vscode.Uri): Promise<string | undefined> {
	const start = uri?.fsPath ?? vscode.workspace.workspaceFolders?.[0]?.uri.fsPath;
	for (let dir = start; dir; ) {
		try {
			await fs.access(path.join(dir, "cmd", "modules.go"));
			return dir;
		} catch {
			const parent = path.dirname(dir);
			dir = parent === dir ? undefined : parent;
		}
	}
	return undefined;
}
